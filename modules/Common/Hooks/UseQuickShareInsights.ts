export function useQuickShareInsights(
  summary: MonthSummary | undefined,
  monthLabel: string | undefined,
) {
  const [isGenerating, setIsGenerating] = useState(false);

  const shareInsights = useCallback(async () => {
    if (isGenerating || !summary || !monthLabel) return;
    try {
      setIsGenerating(true);
      const html = buildHTML(summary, monthLabel);
      const { uri } = await Print.printToFileAsync({ html, base64: false });
      const available = await Sharing.isAvailableAsync();
      if (!available) return;
      await Sharing.shareAsync(uri, {
        mimeType: "application/pdf",
        dialogTitle: "Share insights",
        UTI: "com.adobe.pdf",
      });
    } catch (err) {
      console.error("PDF share failed:", err);
    } finally {
      setIsGenerating(false);
    }
  }, [summary, monthLabel, isGenerating]);

  return { shareInsights, isGenerating };
}
